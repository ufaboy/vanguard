/**
 * Compares Astro-built pages (site/dist) with the current hand-written / generated pages (public/)
 * after normalizing formatting: whitespace, void-tag slashes, attribute quoting and JSON-LD layout.
 *
 *   node scripts/compare.mjs about.html es/about.html index.html es/index.html
 */
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = (p) => fileURLToPath(new URL(p, import.meta.url));
const decode = (s) => s.replace(/&(amp|lt|gt|quot|#39|#x27);/g, (m, e) => ({ amp: '&', lt: '<', gt: '>', quot: '"', '#39': "'", '#x27': "'" })[e]);

function canonical(html) {
  const out = [];
  const re = /<!--([\s\S]*?)-->|<(script|style)\b([^>]*)>([\s\S]*?)<\/\2>|<([^>]+)>|([^<]+)/gi;
  let m;
  while ((m = re.exec(html))) {
    if (m[1] !== undefined) {
      if (/prerender|Generated by/.test(m[1])) continue;
      out.push(`<!--${m[1].trim()}-->`);
    } else if (m[2]) {
      const attrs = tagAttrs(m[3]);
      let body = m[4].trim();
      if (/json/.test(attrs)) body = JSON.stringify(JSON.parse(body));
      else body = body.replace(/\s+/g, ' ');
      out.push(`<${m[2].toLowerCase()}${attrs}>${body}</${m[2].toLowerCase()}>`);
    } else if (m[5]) {
      const [, name, rest = ''] = m[5].match(/^(\/?[\w!-]+)([\s\S]*)$/) || [, m[5]];
      out.push(`<${name.toLowerCase()}${tagAttrs(rest)}>`);
    } else {
      const text = decode(m[6]).replace(/\s+/g, ' ').trim();
      if (text) out.push(text);
    }
  }
  return out;
}

function tagAttrs(raw) {
  const attrs = [];
  const re = /([^\s=/]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+)))?/g;
  let m;
  while ((m = re.exec(raw.replace(/\/\s*$/, '')))) attrs.push(`${m[1].toLowerCase()}="${decode(m[2] ?? m[3] ?? m[4] ?? '')}"`);
  return attrs.length ? ` ${attrs.join(' ')}` : '';
}

let total = 0;
for (const file of process.argv.slice(2)) {
  const a = canonical(fs.readFileSync(root(`../../public/${file}`), 'utf8'));
  const b = canonical(fs.readFileSync(root(`../dist/${file}`), 'utf8'));
  const diffs = [];
  const len = Math.max(a.length, b.length);
  for (let i = 0, j = 0; i < len || j < len; i++, j++) {
    if (a[i] === b[j]) continue;
    // Resync on a short insertion/deletion.
    const ahead = b.indexOf(a[i], j);
    const behind = a.indexOf(b[j], i);
    if (ahead !== -1 && ahead - j <= 3) { for (; j < ahead; j++) diffs.push(`+ ${b[j]}`); continue; }
    if (behind !== -1 && behind - i <= 3) { for (; i < behind; i++) diffs.push(`- ${a[i]}`); continue; }
    if (a[i] !== undefined) diffs.push(`- ${a[i]}`);
    if (b[j] !== undefined) diffs.push(`+ ${b[j]}`);
    if (diffs.length > 40) break;
  }
  total += diffs.length;
  console.log(`${diffs.length ? '✗' : '✓'} ${file}: ${a.length} nodes, ${diffs.length} differing`);
  for (const d of diffs) console.log(`    ${d.slice(0, 220)}`);
}
process.exit(total ? 1 : 0);
